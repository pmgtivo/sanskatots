"""Markdown renderer — the filing pack you read while typing into the portal.

Ordering is deliberate: anything that blocks filing comes first, then the exact
boxes in portal order, then the workings that justify them, then provenance.
"""

from __future__ import annotations

from typing import Any, Dict, List, Sequence

from . import rules

SEV_ICON = {"error": "[BLOCKER]", "warning": "[CHECK]", "info": "[FYI]"}


def money(value: Any) -> str:
    """Indian digit grouping, two decimals, explicit sign on negatives."""
    try:
        amount = float(value)
    except (TypeError, ValueError):
        return "-"
    negative = amount < 0
    amount = abs(amount)
    whole = int(amount)
    frac = int(round((amount - whole) * 100))
    if frac == 100:
        whole += 1
        frac = 0
    digits = str(whole)
    if len(digits) > 3:
        head, tail = digits[:-3], digits[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        digits = ",".join(parts + [tail])
    return "%s%s.%02d" % ("-" if negative else "", digits, frac)


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> List[str]:
    out = ["| " + " | ".join(str(h) for h in headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join("" if c is None else str(c) for c in row) + " |")
    return out


def render(result: Dict[str, Any], provenance: Dict[str, Any]) -> str:
    L: List[str] = []
    seller = result.get("seller", {})
    totals = result.get("totals", {})
    tables = result.get("tables", {})
    anomalies = result.get("anomalies", [])

    L.append("# GST Filing Pack — %s" % result.get("label", ""))
    L.append("")
    L.append("| | |")
    L.append("| --- | --- |")
    L.append("| Legal name | %s |" % seller.get("legal_name", ""))
    L.append("| GSTIN | `%s` |" % seller.get("gstin", ""))
    L.append("| State | %s (code %s) |" % (seller.get("state", ""), seller.get("state_code", "")))
    L.append("| Tax period(s) | %s |" % ", ".join(result.get("periods", [])))
    L.append("| Scheme | %s |" % result.get("filing", {}).get("frequency", "").upper())
    L.append("")
    L.append("> Generated by PnL Studio -> GST module. Every figure below is "
             "computed from the marketplace GST reports on disk; nothing is "
             "typed in by hand. File these numbers yourself on the portal.")
    L.append("")

    # ---- due dates -------------------------------------------------
    filing = result.get("filing", {})
    if filing.get("due"):
        L.append("## Due dates")
        L.append("")
        L += _table(["Form", "Due", "Rule"],
                    [[d["form"], "**%s**" % d["due"], d["rule"]] for d in filing["due"]])
        L.append("")
        L.append("_%s_" % filing.get("time_bar", ""))
        L.append("")

    # ---- blockers first --------------------------------------------
    errors = [a for a in anomalies if a["severity"] == "error"]
    warnings = [a for a in anomalies if a["severity"] == "warning"]
    L.append("## Before you file")
    L.append("")
    if not anomalies:
        L.append("No anomalies detected. Every line reconciled.")
    else:
        L.append("%d blocker(s), %d check(s)." % (len(errors), len(warnings)))
    L.append("")
    for item in errors + warnings:
        L.append("### %s %s" % (SEV_ICON.get(item["severity"], ""), item["code"]))
        L.append("")
        L.append(item["message"])
        detail = item.get("detail")
        if isinstance(detail, list) and detail:
            L.append("")
            keys = list(detail[0].keys())
            L += _table(keys, [[money(r[k]) if isinstance(r[k], float) else r[k]
                                for k in keys] for r in detail])
        elif isinstance(detail, dict) and detail:
            L.append("")
            L += _table(["key", "count"], [[k, v] for k, v in detail.items()])
        L.append("")

    # ---- headline ---------------------------------------------------
    L.append("## Headline")
    L.append("")
    allt = totals.get("all", {})
    L += _table(
        ["Measure", "Value (Rs)"],
        [
            ["Net outward supplies (invoices less credit notes)", money(allt.get("taxable"))],
            ["  of which exempt (books)", money(totals.get("exempt", {}).get("taxable"))],
            ["  of which nil rated", money(totals.get("nil_rated", {}).get("taxable"))],
            ["  of which taxable", money(totals.get("taxable", {}).get("taxable"))],
            ["  of which non-GST", money(totals.get("non_gst", {}).get("taxable"))],
            ["Gross supplies before returns", money(totals.get("invoices", {}).get("taxable"))],
            ["Credit notes (returns / refunds)", money(totals.get("credit_notes", {}).get("taxable"))],
            ["**GST payable this period**",
             "**%s**" % money(tables.get("gstr3b", {}).get("tax_payable", {}).get("total"))],
        ])
    L.append("")

    # ---- GSTR-1 -----------------------------------------------------
    L.append("---")
    L.append("")
    L.append("## FORM GSTR-1")
    L.append("")

    t8 = tables.get("gstr1_table_8", {})
    L.append("### %s" % t8.get("title", ""))
    L.append("")
    L += _table(["Row", "Description", "Nil Rated", "Exempted", "Non-GST", "Total"],
                [[r["row"], r["description"], money(r["nil_rated"]),
                  "**%s**" % money(r["exempted"]), money(r["non_gst"]),
                  money(r["total"])] for r in t8.get("rows", [])])
    L.append("")
    L.append("Table 8 total: **Rs %s**" % money(t8.get("total")))
    L.append("")
    L.append("> %s" % t8.get("note", ""))
    L.append("")

    t7 = tables.get("gstr1_table_7", {})
    L.append("### %s" % t7.get("title", ""))
    L.append("")
    if t7.get("intra_state"):
        L.append("**7A(1) — Intra-State supplies (consolidated, rate-wise)**")
        L.append("")
        L += _table(["Rate %", "Taxable value", "CGST", "SGST", "Cess"],
                    [[r["rate_pct"], money(r["taxable"]), money(r["cgst"]),
                      money(r["sgst"]), money(r["cess"])] for r in t7["intra_state"]])
        L.append("")
    if t7.get("inter_state"):
        L.append("**7B(1) — Inter-State supplies, place of supply wise**")
        L.append("")
        L += _table(["POS code", "Place of supply", "Rate %", "Taxable value", "IGST", "Cess"],
                    [[r["pos_code"], r["pos_state"], r["rate_pct"],
                      money(r["taxable"]), money(r["igst"]), money(r["cess"])]
                     for r in t7["inter_state"]])
        L.append("")
    if not t7.get("intra_state") and not t7.get("inter_state"):
        L.append("Nil — no taxable B2C supplies in this period.")
        L.append("")
    L.append("> %s" % t7.get("note", ""))
    L.append("")

    t5 = tables.get("gstr1_table_5", {})
    L.append("### %s" % t5.get("title", ""))
    L.append("")
    if t5.get("rows"):
        L += _table(["Invoice", "POS", "Rate %", "Taxable", "IGST", "Cess"],
                    [[r["invoice_no"], r["pos_state"], r["rate_pct"],
                      money(r["taxable"]), money(r["igst"]), money(r["cess"])]
                     for r in t5["rows"]])
    else:
        L.append("Nil. _%s_" % t5.get("note", ""))
    L.append("")

    t12 = tables.get("gstr1_table_12", {})
    L.append("### %s (%d-digit)" % (t12.get("title", ""), t12.get("digits", 4)))
    L.append("")
    for heading, key in (("B2C", "b2c"), ("B2B", "b2b")):
        rows = t12.get(key, [])
        if not rows:
            continue
        L.append("**%s**" % heading)
        L.append("")
        L += _table(["HSN", "Description", "UQC", "Rate %", "Qty",
                     "Total value", "Taxable value", "IGST", "CGST", "SGST", "Cess"],
                    [[r["hsn"], r["description"], r["uqc"], r["rate_pct"],
                      money(r["quantity"]), money(r["total_value"]),
                      money(r["taxable"]), money(r["igst"]), money(r["cgst"]),
                      money(r["sgst"]), money(r["cess"])] for r in rows])
        L.append("")
    L.append("> %s" % t12.get("note", ""))
    L.append("")

    t13 = tables.get("gstr1_table_13", {})
    L.append("### %s" % t13.get("title", ""))
    L.append("")
    L += _table(["Source", "Nature of document", "Serial from", "Serial to",
                 "Total number", "Cancelled", "Net issued", "Notes"],
                [[r["platform"], r["document"],
                  r["from"] or "(not numbered)", r["to"] or "(not numbered)",
                  r["total"], r["cancelled"], r["count"],
                  "; ".join(
                      (["missing: " + ", ".join(r["missing"])] if r["missing"] else [])
                      + (["CHECK - not accounted for: " + ", ".join(r["missing_unexplained"])]
                         if r["missing_unexplained"] else [])
                      + list(r.get("notes") or []))]
                 for r in t13.get("rows", [])])
    L.append("")
    L.append("> %s" % t13.get("note", ""))
    L.append("")

    t14 = tables.get("gstr1_table_14", {})
    L.append("### %s" % t14.get("title", ""))
    L.append("")
    L += _table(["Operator", "ECO GSTIN", "Enter in Table 14?",
                 "Net value of taxable supplies", "TCS collected",
                 "Net value (all supplies)"],
                [[r["eco_name"] or r["platform"], r["eco_gstin"] or "(not configured)",
                  "YES" if r.get("enter") else "no - nothing taxable",
                  money(r["net_value_taxable"]), money(r.get("tcs", 0.0)),
                  money(r["net_value_all"])]
                 for r in t14.get("rows", [])])
    L.append("")
    L.append("> %s" % t14.get("note", ""))
    L.append("")

    # ---- GSTR-3B ----------------------------------------------------
    L.append("---")
    L.append("")
    L.append("## FORM GSTR-3B")
    L.append("")
    g3b = tables.get("gstr3b", {})
    L.append("### %s" % g3b.get("title", ""))
    L.append("")
    L += _table(["Row", "Nature of supply", "Taxable value", "IGST", "CGST", "SGST", "Cess"],
                [[r["row"], r["description"], money(r["taxable"]), money(r["igst"]),
                  money(r["cgst"]), money(r["sgst"]), money(r["cess"])]
                 for r in g3b.get("rows", [])])
    L.append("")
    payable = g3b.get("tax_payable", {})
    L.append("**Tax payable in cash this period: IGST %s | CGST %s | SGST %s | Cess %s | TOTAL Rs %s**"
             % (money(payable.get("igst")), money(payable.get("cgst")),
                money(payable.get("sgst")), money(payable.get("cess")),
                money(payable.get("total"))))
    L.append("")
    L.append("> %s" % g3b.get("note", ""))
    L.append("")

    g32 = tables.get("gstr3b_3_2", {})
    L.append("### %s" % g32.get("title", ""))
    L.append("")
    if g32.get("rows"):
        L += _table(["POS code", "Place of supply", "Taxable value", "IGST"],
                    [[r["pos_code"], r["pos_state"], money(r["taxable"]), money(r["igst"])]
                     for r in g32["rows"]])
    else:
        L.append("Nil.")
    L.append("")
    L.append("> %s" % g32.get("note", ""))
    L.append("")

    itc = tables.get("itc", {})
    L.append("### %s" % itc.get("title", ""))
    L.append("")
    L.append("Exempt share of turnover: **%.2f%%** (Rs %s of Rs %s)"
             % (itc.get("exempt_share_pct", 0.0), money(itc.get("exempt_turnover")),
                money(itc.get("total_turnover"))))
    L.append("")
    for line in itc.get("guidance", []):
        L.append("- %s" % line)
    L.append("")
    L.append("> %s" % itc.get("note", ""))
    L.append("")

    # ---- TCS --------------------------------------------------------
    L.append("---")
    L.append("")
    tcs = tables.get("tcs", {})
    L.append("## %s" % tcs.get("title", ""))
    L.append("")
    L += _table(["Operator", "Net taxable supplies", "Net exempt supplies",
                 "TCS collected", "TCS expected @%.2f%%" % (tcs.get("rate", 0) * 100),
                 "Variance"],
                [[r["platform"], money(r["net_taxable_supplies"]),
                  money(r["net_exempt_supplies"]), money(r["tcs_collected"]),
                  money(r["tcs_expected"]), money(r["variance"])]
                 for r in tcs.get("rows", [])])
    L.append("")
    L.append("Total TCS to claim: **Rs %s** — _%s_"
             % (money(tcs.get("total_collected")), tcs.get("citation", "")))
    L.append("")
    L.append("> %s" % tcs.get("note", ""))
    L.append("")

    # ---- workings ---------------------------------------------------
    L.append("---")
    L.append("")
    L.append("## Workings")
    L.append("")
    L.append("### Month by month")
    L.append("")
    L += _table(["Period", "Lines", "Qty", "Exempt", "Taxable", "Tax", "Net supplies"],
                [[p["label"], p["total"]["lines"], money(p["total"]["quantity"]),
                  money(p["exempt"]["taxable"]), money(p["taxable"]["taxable"]),
                  money(p["total"]["tax"]), money(p["total"]["taxable"])]
                 for p in result.get("by_period", [])])
    L.append("")

    L.append("### By marketplace")
    L.append("")
    L += _table(["Platform", "Supplies", "Credit notes", "Net", "Exempt",
                 "Taxable", "Cancelled", "Replacements", "TCS"],
                [[p["platform"], money(p["invoices"]["taxable"]),
                  money(p["credit_notes"]["taxable"]), money(p["total"]["taxable"]),
                  money(p["exempt"]["taxable"]), money(p["taxable"]["taxable"]),
                  p["cancelled"], p["replacements"], money(p["tcs_collected"])]
                 for p in result.get("by_platform", [])])
    L.append("")
    L.append("> Cancelled orders never produced an invoice and free replacements "
             "carry no consideration, so neither appears in any turnover box. "
             "They are listed only so the line counts reconcile to the raw files.")
    L.append("")

    L.append("### By place of supply")
    L.append("")
    L += _table(["Code", "State", "Type", "Lines", "Qty", "Net value", "Tax"],
                [[s["pos_code"], s["pos_state"], s["supply_type"], s["lines"],
                  money(s["quantity"]), money(s["taxable"]), money(s["tax"])]
                 for s in result.get("by_state", [])])
    L.append("")

    # ---- legal ------------------------------------------------------
    L.append("---")
    L.append("")
    L.append("## Basis of classification")
    L.append("")
    L += _table(["HSN", "Description", "Treatment", "Authority"],
                [[hsn, desc, "Exempt", cite]
                 for hsn, (desc, cite) in sorted(rules.EXEMPT_HSN.items())])
    L.append("")
    L.append("- **Exempt, not nil-rated.** Printed books are exempted under "
             "section 11 via Notfn. 2/2017-CT(R). They are absent from the rate "
             "notification 1/2017, which is what 'nil rated' means. The GSTR-1 "
             "Table 8 column differs; the GSTR-3B box (3.1(c)) is the same.")
    L.append("- **No ITC.** Section 17(2) blocks credit attributable to exempt "
             "supplies, so the 18% GST on marketplace commission is a cost.")
    L.append("- **Bill of supply, not tax invoice.** Section 31(3)(c) read with "
             "rule 49 applies to exempt supplies.")
    L.append("- **No TCS on exempt supplies.** Section 52(1) charges TCS on the "
             "net value of *taxable* supplies only.")
    L.append("- **Registration still mandatory.** Section 24(ix) requires "
             "registration for persons supplying goods through an e-commerce "
             "operator.")
    L.append("")
    L.append("> %s" % rules.VERIFY_SOURCES)
    L.append("")

    # ---- provenance -------------------------------------------------
    L.append("---")
    L.append("")
    L.append("## Source files")
    L.append("")
    L += _table(["File", "Platform", "Rows", "Note"],
                [[f["rel"], f["platform"], f["rows"],
                  "; ".join([f["skipped"]] * bool(f["skipped"]) + list(f.get("notes") or []))]
                 for f in provenance.get("files", [])])
    L.append("")
    L.append("Rows parsed %d -> %d after de-duplication (%d dropped)."
             % (provenance.get("rows_before_dedupe", 0),
                provenance.get("rows_after_dedupe", 0),
                provenance.get("rows_dropped", 0)))
    L.append("")
    if provenance.get("errors"):
        L.append("**Files that failed to parse:**")
        L.append("")
        L += _table(["File", "Error"],
                    [[e["file"], e["error"]] for e in provenance["errors"]])
        L.append("")

    missing = [p for p in ("amazon", "flipkart", "meesho")
               if p not in {f["platform"] for f in provenance.get("files", [])}]
    if missing:
        L.append("**No data found for:** %s. Totals exclude these marketplaces."
                 % ", ".join(missing))
        L.append("")

    return "\n".join(L).rstrip() + "\n"
